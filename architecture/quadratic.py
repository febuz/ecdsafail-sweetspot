"""Exact parity-product decomposition of a quadratic Boolean ANF.

The polar matrix is alternating over GF(2). Removing one hyperbolic
pair eliminates two pivot rows/columns. Linear terms generated by
x_i**2 = x_i are retained explicitly.
"""


def parity_product(left, right):
    terms = set()
    for i in range(left.bit_length()):
        if left >> i & 1:
            for j in range(right.bit_length()):
                if right >> j & 1:
                    term = (1 << i) | (1 << j)
                    terms.symmetric_difference_update({term})
    return terms


def decompose(function):
    remaining = set(function.terms)
    factors = []
    while edges := sorted(term for term in remaining if term.bit_count() == 2):
        pivot = edges[0]
        i, j = [bit for bit in range(pivot.bit_length()) if pivot >> bit & 1]
        left = right = 0
        for edge in edges:
            if edge >> j & 1:
                left ^= edge ^ (1 << j)
            if edge >> i & 1:
                right ^= edge ^ (1 << i)
        factors.append((left, right))
        remaining.symmetric_difference_update(parity_product(left, right))
    return tuple(factors), frozenset(remaining)


def parity_basis(left, right):
    """CNOT basis change, two host wires, then inverse restores all inputs."""
    left, right = tuple(left), tuple(right)
    if not left or not right or len(set(left)) != len(left) or len(set(right)) != len(right):
        raise ValueError("Parity supports must be nonempty sets")
    if set(left) == set(right):
        raise ValueError("Equal parity factors reduce to a linear term")
    if set(left).isdisjoint(right):
        return [(wire, left[0]) for wire in left[1:]] + [(wire, right[0]) for wire in right[1:]], left[0], right[0]
    wires = sorted(set(left) | set(right))
    vectors = [sum(1 << wires.index(wire) for wire in side) for side in (left, right)]
    independent = {}
    rows = []
    def append_if_independent(value):
        reduced = value
        for pivot in sorted(independent, reverse=True):
            if reduced >> pivot & 1:
                reduced ^= independent[pivot]
        if not reduced:
            return
        independent[reduced.bit_length() - 1] = reduced
        rows.append(value)
    for vector in vectors:
        append_if_independent(vector)
    for index in range(len(wires)):
        append_if_independent(1 << index)
    if len(rows) != len(wires):
        raise AssertionError("Cannot complete a parity basis")
    elimination = []
    for column in range(len(wires)):
        pivot = next(index for index in range(column, len(wires)) if rows[index] >> column & 1)
        if pivot != column:
            rows[pivot], rows[column] = rows[column], rows[pivot]
            elimination += [(wires[column], wires[pivot]), (wires[pivot], wires[column]), (wires[column], wires[pivot])]
        for index in range(len(wires)):
            if index != column and rows[index] >> column & 1:
                rows[index] ^= rows[column]
                elimination.append((wires[column], wires[index]))
    assert rows == [1 << index for index in range(len(wires))]
    return list(reversed(elimination)), wires[0], wires[1]
